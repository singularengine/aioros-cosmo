def chart_config(name):
    """The example's chartConfig as c:ChartConfig entries: each data key's label and its color's theme key (var(--chart-n) is
    PictorPalette{n}); the browsers' entries, which a pie's NameKey and Cells name instead, are left out."""
    text = (REGISTRY / f"{name}.tsx").read_text()
    block = re.search(r"const chartConfig = \{(.*?)\n\} satisfies ChartConfig", text, re.S).group(1)
    entries = []
    for key, body in re.findall(r"\n  (\w+): \{(.*?)\n  \}", block, re.S):
        if key not in KEYS or key in ("month", "date", "browser", "label"):
            continue
        label = re.search(r'label: "([^"]+)"', body)
        color = re.search(r'color: "var\(--chart-(\d)\)"', body)
        entries.append((KEYS[key], label.group(1) if label else None, f"PictorPalette{color.group(1)}" if color else None))
    return entries


def configured(name, body):
    """A fixture given its chartConfig: the config as a resource of its card, the charts reading it (c:ChartConfig.Config), and
    each series' name and paint left to it where they are the config's."""
    entries = chart_config(name)
    if not entries:
        return body
    items = "".join(f'<c:ChartConfigItem Key="{key}"' + (f' Label="{label}"' if label else "") + (f' Color="{color}"' if color else "") + " />" for key, label, color in entries)
    body = re.sub(r'(<Border x:DataType="m:Chart(?:Samples|Interactive)">)', lambda m: f'{m.group(1)}\n          <Border.Resources><c:ChartConfig x:Key="ChartConfig">{items}</c:ChartConfig></Border.Resources>', body, count=1)
    body = re.sub(r"<p:(\w+Chart) ", r'<p:\1 c:ChartConfig.Config="{StaticResource ChartConfig}" ', body)
    for key, label, color in entries:
        def series(match):
            tag = match.group(0)
            if label:
                tag = tag.replace(f' Name="{label}"', "")
            if color:
                kind = match.group(1)
                paints = ["Stroke"] if kind == "Line" else ["Fill", "Stroke"] if kind == "Area" else ["Fill"]
                for paint in paints:
                    tag = tag.replace(f' {paint}="{{DynamicResource {color}}}"', "")
            return tag
        body = re.sub(rf'<p:(Bar|Line|Area|Radar|RadialBar) DataKey="{key}"[^>]*>', series, body)
    return body


for _name in list(FIXTURES):
    FIXTURES[_name] = configured(_name, FIXTURES[_name])


