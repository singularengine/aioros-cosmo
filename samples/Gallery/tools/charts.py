def browser_months():
    """The Gallery's own five-series data (no shadcn/ui example has more than two series): chart-pie-simple's visitors per
    browser, grown month by month from January to June, for a tooltip of five lines."""
    visitors = [int(row["visitors"]) for row in rows("chart-pie-simple")]
    entries = []
    for month, growth in enumerate(GROWTH):
        members = ", ".join(f"{name} = {round(count * growth)}" for name, count in zip(BROWSERS, visitors))
        entries.append(f"        new() {{ Month = new DateTime(2024, {month + 1}, 1), {members} }},")
    return "\n".join(entries)


