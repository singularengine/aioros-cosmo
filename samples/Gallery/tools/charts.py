KEYS = {"month": "Month", "date": "Date", "browser": "Browser", "label": "Label", "desktop": "Desktop", "mobile": "Mobile", "visitors": "Visitors",
        "running": "Running", "swimming": "Swimming"}
MONTHS = ["january", "february", "march", "april", "may", "june", "july", "august", "september", "october", "november", "december"]


def rows(name):
    text = (REGISTRY / f"{name}.tsx").read_text()
    data = re.search(r"const chartData = \[(.*?)\]\n", text, re.S).group(1)
    labels = dict(re.findall(r'(\w+): \{\s*label: "([^"]+)"', text))
    found = [{key: raw.strip() for key, raw in re.findall(r'(\w+): "?([^",}]+)"?', row)} for row in re.findall(r"\{([^{}]*)\}", data)]
    for row in found:
        if "browser" in row:
            row["label"] = labels.get(row["browser"], row["browser"])
    return found


def value(key, raw):
    if key == "month":
        return f"new DateTime(2024, {MONTHS.index(raw.lower()) + 1}, 1)"
    if key == "date":
        return f"DateTime.Parse(\"{raw}\", CultureInfo.InvariantCulture)"
    if key in ("browser", "label"):
        return f"\"{raw}\""
    return raw


def literal(name):
    entries = []
    for row in rows(name):
        members = ", ".join(f"{KEYS[key]} = {value(key, raw)}" for key, raw in row.items() if key in KEYS)
        entries.append(f"        new() {{ {members} }},")
    return "\n".join(entries)


